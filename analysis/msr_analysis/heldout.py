"""Four-part training-homology holdout filter across all held-out benchmarks.

``reference/tsuboyama_rule_flags.csv`` (generated by ``leak_audit/21_tsuboyama_rule.py``) records, for every
ProteinGym assay, Domainome domain, MGnify scaffold, and Rocklin de novo design, the four criteria that built
the Homology-Restricted MegaScale split against the 172 training libraries:

    MMseqs2 E-value <= 1e-3  |  identity > 0.40  |  Foldseek E-value <= 1e-3  |  Foldseek TM-score > 0.70

Every held-out evaluation filters out homologous items through ``excluded(dataset)`` or ``keep_ids(dataset)``.
"""
from __future__ import annotations

import pandas as pd

from .paths import REFERENCE

DATASETS = ('proteingym', 'domainome', 'mgnify', 'rocklin_denovo')
_CACHE: dict[str, pd.DataFrame] = {}


def flags() -> pd.DataFrame:
    """Return the full ``tsuboyama_rule_flags.csv`` DataFrame (cached in memory; returns a copy-safe view)."""
    if 'f' not in _CACHE:
        _CACHE['f'] = pd.read_csv(REFERENCE / 'tsuboyama_rule_flags.csv', dtype={'item_id': str})
    return _CACHE['f']


def excluded(dataset: str) -> set[str]:
    """Return the set of ``item_id`` strings in ``dataset`` homologous to the training libraries."""
    if dataset not in DATASETS:
        raise ValueError(f'Unknown heldout dataset {dataset!r}; expected one of {DATASETS}')
    f = flags()
    return set(f.loc[(f['dataset'] == dataset) & f['homologous'].astype(bool), 'item_id'].astype(str))


def keep_ids(dataset: str) -> set[str]:
    """Return the set of held-out (non-homologous) ``item_id`` strings in ``dataset``."""
    if dataset not in DATASETS:
        raise ValueError(f'Unknown heldout dataset {dataset!r}; expected one of {DATASETS}')
    f = flags()
    return set(f.loc[(f['dataset'] == dataset) & ~f['homologous'].astype(bool), 'item_id'].astype(str))
