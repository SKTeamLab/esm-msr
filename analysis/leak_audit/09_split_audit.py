"""Validate the Homology-Restricted MegaScale split (``splits_oct06_capped``):
does the composite sequence + structure rule hold across both internal splits and quarantined
external benchmarks, and how sensitive is it to threshold relaxation?

Uses ``homology_pairs.csv`` (generated by ``preprocessing/split_tsuboyama.py``) and
``data/splits_oct06_capped_library_assignment.csv``.
"""
import json
import os
import pickle
import sys

import networkx as nx
import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import LEAK_ROOT, OUT_DIR, REPO_ROOT, WORK_DATA_DIR

os.makedirs(OUT_DIR, exist_ok=True)
default_pairs = os.path.join(
    LEAK_ROOT,
    'analysis',
    'salvaged_2026-10-16',
    'structure-homology-splits-e5ca04',
    'data',
    'tsuboyama',
    'homology',
    'homology_pairs.csv',
)
PAIRS = os.environ.get(
    'HOMOLOGY_PAIRS_CSV',
    default_pairs if os.path.exists(default_pairs) else os.path.join(WORK_DATA_DIR, 'homology_pairs.csv'),
)
pairs = pd.read_csv(PAIRS)
la = pd.read_csv(os.path.join(REPO_ROOT, 'data', 'splits_oct06_capped_library_assignment.csv'), index_col=0)
split = pickle.load(open(os.path.join(WORK_DATA_DIR, 'capped_split_sets.pkl'), 'rb'))

assign = la['split'].to_dict()
func5 = ['GRB2', 'DLG4', 'EstA', 'Myo', 'GB1']
extids = sorted({x for x in set(pairs['a']) | set(pairs['b']) if str(x).startswith('test_')})
extall = set(extids) | set(func5)
for x in extall:
    assign[x] = 'external'

n_libs = sum(1 for x, v in assign.items() if v in ('train', 'val', 'test', 'excluded'))
print(f'external proteins in pair table: {len(extids)} classical + {len(func5)} functional DMS = {len(extall)}; libraries: {n_libs}')

res = {
    'n_libraries_total': int(n_libs),
    'n_external_classical_nodes': int(len(extids)),
    'n_external_dms_nodes': int(len(func5)),
    'n_external_nodes_total': int(len(extall)),
}


def edges(df, seq_e=1e-3, st_e=1e-3, ident=0.40, tm=None, tm_norm='max'):
    m = (df['seq_evalue'] <= seq_e) | (df['struct_evalue'] <= st_e)
    if ident is not None:
        m |= df['identity'] > ident
    if tm is not None:
        m |= df[f'struct_tm_{tm_norm}'] > tm
    return m.fillna(False)


def cross(df, mask):
    d = df.loc[mask].copy()
    d['sa'] = d['a'].map(assign)
    d['sb'] = d['b'].map(assign)
    return d[d['sa'].notna() & d['sb'].notna() & (d['sa'] != d['sb']) & ~((d['sa'] == 'external') & (d['sb'] == 'external'))]


cfg = dict(seq_e=1e-3, st_e=1e-3, ident=0.40, tm=0.70)
m = edges(pairs, **cfg)
cross_d = cross(pairs, m)
real = cross_d[~cross_d['sa'].isin(['excluded']) & ~cross_d['sb'].isin(['excluded'])]
res['default_edges_total'] = int(m.sum())
res['default_cross_edges_involving_excluded'] = int(len(cross_d))
res['default_cross_edges_real'] = int(len(real))
print('default rule (E<=1e-3 | id>0.40 | TM_max>0.70): edges=', int(m.sum()), 'cross(any)=', len(cross_d), 'cross(non-excluded)=', len(real))

# Sensitivity sweep across both internal {train, val, test} and quarantined external benchmarks
sweep = []
internal_sets = {'train', 'val', 'test'}
for name, kw in [
    ('split rule + TM>0.70 (actual)', dict(seq_e=1e-3, st_e=1e-3, ident=0.40, tm=0.70)),
    ('E<=1e-3 or id>0.40 (no TM cap)', dict(seq_e=1e-3, st_e=1e-3, ident=0.40)),
    ('E<=1e-3 only', dict(seq_e=1e-3, st_e=1e-3, ident=None)),
    ('identity>0.30', dict(seq_e=1e-9, st_e=1e-9, ident=0.30)),
    ('identity>0.25', dict(seq_e=1e-9, st_e=1e-9, ident=0.25)),
    ('E<=1e-2', dict(seq_e=1e-2, st_e=1e-2, ident=None)),
    ('E<=1e-1', dict(seq_e=1e-1, st_e=1e-1, ident=None)),
    ('TM_max>0.50', dict(seq_e=1e-9, st_e=1e-9, ident=None, tm=0.50)),
    ('TM_max>0.40', dict(seq_e=1e-9, st_e=1e-9, ident=None, tm=0.40)),
]:
    mm = edges(pairs, **kw)
    cc = cross(pairs, mm)
    rr = cc[~cc['sa'].isin(['excluded']) & ~cc['sb'].isin(['excluded'])]
    rr_int = rr[rr['sa'].isin(internal_sets) & rr['sb'].isin(internal_sets)]
    rr_ext = rr[(rr['sa'] == 'external') ^ (rr['sb'] == 'external')]
    sweep.append(dict(
        rule=name,
        edges=int(mm.sum()),
        cross_any=int(len(cc)),
        cross_real=int(len(rr)),
        cross_internal=int(len(rr_int)),
        cross_external=int(len(rr_ext)),
        pairs=int(len(rr)),
    ))
    print(
        f'{name:32s} edges={int(mm.sum()):6d} cross_any={len(cc):5d} '
        f'cross_non_excl={len(rr):5d} (internal={len(rr_int):4d}, external={len(rr_ext):4d})'
    )
res['sweep'] = sweep

# Structure-only value (Foldseek E<=1e-3 or TM_max>0.70 without MMseqs E<=1e-3 or identity>0.40)
seqm = (pairs['seq_evalue'] <= 1e-3).fillna(False)
idm = (pairs['identity'] > 0.40).fillna(False)
stm_e = (pairs['struct_evalue'] <= 1e-3).fillna(False)
stm_any = stm_e | (pairs['struct_tm_max'] > 0.70).fillna(False)

st_only_e = pairs[stm_e & ~seqm & ~idm]
st_only_any = pairs[stm_any & ~seqm & ~idm]
res['pairs_struct_only'] = int(len(st_only_e))
res['pairs_struct_or_tm70_only'] = int(len(st_only_any))
so_e_cross = cross(st_only_e, pd.Series(True, index=st_only_e.index))
res['struct_only_cross_real'] = int(len(so_e_cross[~so_e_cross['sa'].isin(['excluded']) & ~so_e_cross['sb'].isin(['excluded'])]))
res['struct_only_cross_with_excluded'] = int(len(so_e_cross))
res['struct_only_external'] = int(
    len(so_e_cross[(so_e_cross['sa'].isin(internal_sets) & (so_e_cross['sb'] == 'external')) |
                   (so_e_cross['sb'].isin(internal_sets) & (so_e_cross['sa'] == 'external'))])
)
print('structure-only (E_struct<=1e-3) pairs:', len(st_only_e), 'cross(non-excluded):', res['struct_only_cross_real'], 'cross(with excluded):', len(so_e_cross))

# Connected-component check (post bridge-pruning, excluding dropped nodes)
kept_pairs = pairs.loc[m & ~pairs['a'].map(assign).eq('excluded') & ~pairs['b'].map(assign).eq('excluded')]
g_kept = nx.Graph()
g_kept.add_edges_from(zip(kept_pairs['a'], kept_pairs['b']))
comp_kept = {}
for i, c in enumerate(nx.connected_components(g_kept)):
    for n in c:
        comp_kept[n] = i
comp_kept_ext = {comp_kept[x] for x in extall if x in comp_kept}
res['kept_graph_transitive_external'] = {
    s: sum(1 for lib, sp_s in assign.items() if sp_s == s and lib in comp_kept and comp_kept[lib] in comp_kept_ext)
    for s in ('train', 'val', 'test')
}

# Full unpruned graph (including excluded bridge nodes) to document why 142 libraries were dropped
g_full = nx.Graph()
g_full.add_edges_from(zip(pairs.loc[m, 'a'], pairs.loc[m, 'b']))
comp_full = {}
for i, c in enumerate(nx.connected_components(g_full)):
    for n in c:
        comp_full[n] = i
comp_full_ext = {comp_full[x] for x in extall if x in comp_full}
gap = {s: [] for s in ('train', 'val', 'test')}
for lib, s in assign.items():
    if s in gap and lib in comp_full and comp_full[lib] in comp_full_ext:
        gap[s].append(lib)
res['transitive_connected'] = {k: len(v) for k, v in gap.items()}
print('kept-graph transitive to external:', res['kept_graph_transitive_external'], '; unpruned-graph (via excluded bridges):', res['transitive_connected'])

best = []
for lib in gap['train']:
    sub = pairs[((pairs['a'] == lib) & (pairs['b'].isin(extall))) | ((pairs['b'] == lib) & (pairs['a'].isin(extall)))]
    if len(sub):
        best.append((lib, sub['identity'].max(), sub['struct_tm_max'].max(), sub['seq_evalue'].min(), sub['struct_evalue'].min()))
    else:
        best.append((lib, np.nan, np.nan, np.nan, np.nan))
bt = pd.DataFrame(best, columns=['lib', 'max_identity', 'max_tm', 'min_seq_e', 'min_struct_e'])
res['transitive_direct_stats'] = {
    c: (float(bt[c].max()) if bt[c].notna().any() else None) for c in ('max_identity', 'max_tm')
}
res['transitive_has_no_direct_pair'] = int(bt['max_identity'].isna().sum())

# Decomposition of the 142 excluded libraries: direct/component external homologs vs bridge-pruned nodes
exl = set(la.index[la['split'] == 'excluded'])
ex_raw = pairs[((pairs['a'].isin(exl)) & (pairs['b'].isin(extall))) | ((pairs['b'].isin(exl)) & (pairs['a'].isin(extall)))]
ex_edges = pairs.loc[m & (((pairs['a'].isin(exl)) & (pairs['b'].isin(extall))) | ((pairs['b'].isin(exl)) & (pairs['a'].isin(extall))))]
ex_direct_libs = (set(ex_edges['a']) | set(ex_edges['b'])) & exl

# Component-level quarantine before bridge pruning (any library connected to external without passing through kept splits)
g_ex = nx.Graph()
ex_or_ext = exl | extall
sub_m = pairs.loc[m & pairs['a'].isin(ex_or_ext) & pairs['b'].isin(ex_or_ext)]
g_ex.add_edges_from(zip(sub_m['a'], sub_m['b']))
comp_ex_ext = set()
for c in nx.connected_components(g_ex):
    if c & extall:
        comp_ex_ext |= (c & exl)
bridge_libs = sorted(exl - comp_ex_ext)

res['excluded_libs_total'] = int(len(exl))
res['excluded_direct_raw_prefilter_pairs'] = int(len(ex_raw))
res['excluded_direct_pairs'] = int(len(ex_edges))
res['excluded_libs_with_direct'] = int(len(ex_direct_libs))
res['excluded_external_component_libs'] = int(len(comp_ex_ext))
res['excluded_bridge_libs'] = int(len(bridge_libs))
res['excluded_bridge_lib_names'] = bridge_libs
res['excluded_direct_identity_gt90'] = int((ex_edges['identity'] > 0.9).sum())
res['excluded_direct_tm_gt90'] = int((ex_edges['struct_tm_max'] > 0.9).sum())

print(
    f'excluded libs: {len(exl)} total = {len(comp_ex_ext)} external-homolog ({len(ex_direct_libs)} with direct edge, '
    f'{len(ex_edges)} direct homology edges vs {len(ex_raw)} raw prefilter pairs) + {len(bridge_libs)} modularity bridge-pruned {bridge_libs}'
)
print('of direct homology edges, identity>0.9:', res['excluded_direct_identity_gt90'], 'TM>0.9:', res['excluded_direct_tm_gt90'])

with open(os.path.join(OUT_DIR, 'homology_audit.json'), 'w') as fh:
    json.dump(res, fh, indent=2)
print('saved homology_audit.json')
