def domainome_overlap_domains(classes=('P', 'H')):
    """Domainome domains with same-protein (`P`, incl. exact `M`) or strong 2D/3D homolog (`H`) overlap
    against the 172 Homology-Restricted MegaScale capped-train scaffolds in
    ``reference/leak_audit_structure_homology.csv`` / ``docs/benchmarks/leak_audit_structure_homology.csv``
    (generated by ``analysis/leak_audit/05d_structure_homology.py``:
    MMseqs2 E <= 1e-3 over cov_test >= 0.50, or Foldseek E <= 1e-3 / qTM > 0.70 over qcov >= 0.50).
    Excludes 4 `P` + 60 `H` = 64 domains by default, leaving 458 of 522 domains."""
    ref_csv = REFERENCE / 'leak_audit_structure_homology.csv'
    if not ref_csv.exists():
        ref_csv = HERE.parent / 'docs' / 'benchmarks' / 'leak_audit_structure_homology.csv'
    df = pd.read_csv(ref_csv)
    df = df[(df['dataset'] == 'domainome') & (df['class_with_struct'].isin(classes))]
    return set(df['item_id'].astype(str))


SINGLE_KEY = {'msr': 'msr:wt', 'msrp0': 'msrp0:wt', 'me': 'me1', 'tm': 'tmpnn', 'spurs': 'spurs'}
MULTI_KEY = {'msr': 'msr:comb', 'msrp0': 'msrp0:wt', 'me': 'me2', 'tm': 'tmpnnd', 'spurs': 'spursm'}
FIXED_KEY = {'msrp0': 'msrp0:wt', 'esm3': 'msrrel@0:comb', 'pmpnn': 'pmpnn', 'prosst': 'prosst', 'geoddg': 'geoddg', 'rosetta': 'rosetta'}


def fam_key(fam, fr, mode='default'):
    if fam in FIXED_KEY:
        k = FIXED_KEY[fam]
        return k if k in fr.preds else None
    if mode == 'singles':
        k = SINGLE_KEY[fam]
        return k if k in fr.preds else None
    mm = has_multi(fr)
    if mode == 'composite' and mm:
        ks = SINGLE_KEY[fam]
        kd = MULTI_KEY[fam]
        if ks not in fr.preds or kd not in fr.preds:
            return None
        ck = f'{ks}|{kd}'
        if ck not in fr.preds:
            n1 = (fr.spine['n_mut'] == 1).to_numpy()
            fr.preds[ck] = np.where(n1[None, :], fr.preds[ks], fr.preds[kd])
        return ck
    k = MULTI_KEY[fam] if mm else SINGLE_KEY[fam]
    return k if k in fr.preds else None


def pooled(tau, B, frac):
    rows, reps_store = [], {}
    for ds in POOLED_SETS:
        fr = load_frame(ds)
        sp = fr.spine
        for fam in FAM:
            k = fam_key(fam, fr)
            if k is None:
                continue
            ok = sp['use'].to_numpy() & np.isfinite(fr.preds[k]).all(axis=0)
            y = sp['y'].to_numpy()[ok]
            cl = sp['cluster'].to_numpy()[ok]
            outs = [scr.pooled_screen(p[ok], y, cl, frac, tau, B, seed=5) for p in fr.preds[k]]
            n_seeds = len(outs)
            if n_seeds == 1:
                reps = outs[0]['reps']
            else:
                sw = np.random.default_rng(17).multinomial(n_seeds, np.full(n_seeds, 1.0 / n_seeds), size=B).astype(float) / n_seeds
                reps = np.einsum('sbm,bs->bm', np.stack([o['reps'] for o in outs], axis=0), sw)
            base = np.mean([o['base'] for o in outs], axis=0)
            reps_store[(ds, fam)] = reps
            for j, m in enumerate(('hit_rate', 'best', 'base_rate', 'gain')):
                lo, hi = np.nanquantile(reps[:, j], [.025, .975])
                rows.append(dict(dataset=ds, family=fam, key=k, metric=m, value=float(base[j]), lo=float(lo), hi=float(hi), n=int(ok.sum()),
                                 oracle_best=float(y.max())))
    return pd.DataFrame(rows), reps_store


